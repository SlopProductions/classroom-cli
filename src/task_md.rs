use crate::classroom::{Material, MaterialKind, Submission, Task};
use crate::util::fmt_due_long;
use std::collections::HashMap;
use std::fmt::Write;

fn material_line(m: &Material, local: &HashMap<String, String>) -> String {
    let icon = match m.kind {
        MaterialKind::Drive { .. } => "📄",
        MaterialKind::YouTube => "▶️",
        MaterialKind::Form => "📝",
        MaterialKind::Link => "🔗",
    };
    let title = if m.title.is_empty() {
        m.url.as_deref().unwrap_or("?")
    } else {
        &m.title
    };
    let mut line = match &m.url {
        Some(url) => format!("- {icon} [{title}]({url})"),
        None => format!("- {icon} {title}"),
    };
    if let MaterialKind::Drive { id, .. } = &m.kind
        && let Some(path) = local.get(id)
    {
        let _ = write!(line, " → [`{path}`]({})", path.replace(' ', "%20"));
    }
    line
}

pub fn render(
    course_name: &str,
    task: &Task,
    materials: &[Material],
    sub: Option<&Submission>,
    local: &HashMap<String, String>,
) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# {}\n", task.title);
    let _ = writeln!(s, "| | |\n|---|---|");
    let _ = writeln!(s, "| **Course** | {course_name} |");
    let _ = writeln!(s, "| **Due** | {} |", fmt_due_long(task.due));
    if let Some(p) = task.max_points {
        let _ = writeln!(s, "| **Points** | {p} |");
    }
    if let Some(sub) = sub {
        let _ = writeln!(s, "| **Status** | {} |", sub.state.label());
    }
    let _ = writeln!(s, "| **Link** | {} |", task.link());

    s.push_str("\n## Instructions\n\n");
    match task.description.as_deref().map(str::trim) {
        Some(d) if !d.is_empty() => {
            s.push_str(d);
            s.push('\n');
        }
        _ => s.push_str("_(no description)_\n"),
    }

    if !materials.is_empty() {
        s.push_str("\n## Materials\n\n");
        for m in materials {
            let _ = writeln!(s, "{}", material_line(m, local));
        }
    }

    if let Some(sub) = sub
        && !sub.attachments.is_empty()
    {
        s.push_str("\n## Already attached\n\n");
        for a in &sub.attachments {
            let _ = writeln!(s, "{}", material_line(a, &HashMap::new()));
        }
    }

    s.push_str("\n---\n_Generated by `class get`. `class submit` skips this file, `.class/` and unchanged files in `materials/`._\n");
    s
}
