use crate::Ctx;
use crate::classroom::State;
use crate::progress::{self, Spinner, spin};
use crate::util::{confirm, fmt_due_long, human_size};
use crate::workspace::{self, Collected, SubmissionRecord};
use anyhow::{Result, bail};
use console::style;
use std::path::{Path, PathBuf};

pub struct SubmitArgs {
    pub path: Option<PathBuf>,
    pub dry_run: bool,
    pub yes: bool,
    pub no_turn_in: bool,
}

struct Payload {
    name: String,
    single: Option<String>,
}

fn payload(root: &Path, col: &Collected) -> Payload {
    match col.include.as_slice() {
        [one] => Payload {
            name: one.rsplit('/').next().unwrap_or(one).to_string(),
            single: Some(one.clone()),
        },
        _ => {
            let dir = root
                .file_name()
                .map(|n| n.to_string_lossy().to_string())
                .unwrap_or("task".into());
            Payload {
                name: format!("{dir}.zip"),
                single: None,
            }
        }
    }
}

fn print_files(root: &Path, col: &Collected) {
    if col.include.is_empty() {
        println!("  {}", style("(no files to turn in)").dim());
    }
    for f in &col.include {
        let size = std::fs::metadata(root.join(f))
            .map(|m| human_size(m.len()))
            .unwrap_or_default();
        let note = if col.modified_generated.contains(f) {
            style(" (modified material)").yellow().to_string()
        } else {
            String::new()
        };
        println!("  {} {f} {}{note}", style("+").green(), style(size).dim());
    }
    for f in &col.skipped_generated {
        println!(
            "  {} {}",
            style("-").dim(),
            style(format!("{f} (generated by the CLI)")).dim()
        );
    }
}

fn task_root(path: Option<PathBuf>) -> Result<PathBuf> {
    let start = match path {
        Some(p) => p,
        None => std::env::current_dir()?,
    };
    workspace::find_root(&start)
}

pub fn submit(ctx: &Ctx, args: SubmitArgs) -> Result<()> {
    let root = task_root(args.path)?;
    let mut meta = workspace::load(&root)?;
    let col = workspace::collect(&root, &meta)?;

    println!(
        "{} {} — {}",
        style("↑").cyan(),
        meta.course_name,
        style(&meta.title).bold()
    );
    print_files(&root, &col);
    if col.include.is_empty() {
        bail!("Nothing to turn in, add your files to {}", root.display());
    }
    let p = payload(&root, &col);
    println!(
        "\nWill upload: {}{}",
        style(&p.name).bold(),
        if p.single.is_some() {
            " (single file)"
        } else {
            ""
        }
    );
    if args.dry_run {
        return Ok(());
    }

    let web = ctx.web_for(Some(&meta.account))?;
    let (course, task) = (meta.course_id.clone(), meta.course_work_id.clone());
    let sub = spin("Checking assignment", || web.submission(&course, &task))?;
    let resubmit = sub.state.is_done();
    if resubmit {
        println!(
            "{} the assignment is '{}'. Uploading a new version will unsubmit it and turn it in again.",
            style("Warning:").yellow(),
            sub.state.label()
        );
        if sub.state == State::Returned {
            println!(
                "{}",
                style(
                    "The assignment has already been graded, the teacher will see the resubmission."
                )
                .yellow()
            );
        }
    }
    if !sub.attachments.is_empty() {
        let names: Vec<_> = sub.attachments.iter().map(|a| a.title.as_str()).collect();
        println!(
            "{}",
            style(format!("Already attached: {}", names.join(", "))).dim()
        );
    }
    if !args.yes
        && !confirm(
            if resubmit {
                "Turn in again?"
            } else {
                "Upload?"
            },
            !resubmit,
        )?
    {
        return Ok(());
    }

    let tmp = tempfile::tempdir()?;
    let upload_path = match &p.single {
        Some(rel) => root.join(rel),
        None => {
            let out = tmp.path().join(&p.name);
            spin("Zipping files", || {
                workspace::make_zip(&root, &col.include, &out)
            })?;
            out
        }
    };
    let size = std::fs::metadata(&upload_path)?.len();

    if resubmit {
        spin("Unsubmitting", || web.reclaim(&course, &task))?;
    }
    let bar = progress::bytes(format!("Uploading {}", p.name), size);
    let uploaded = web.upload(&upload_path, &p.name, &bar);
    bar.finish_and_clear();
    let (file_id, mime) = uploaded?;
    let mut record = SubmissionRecord {
        at: chrono::Local::now().to_rfc3339(),
        file_name: p.name.clone(),
        drive_file_id: file_id.clone(),
        drive_link: Some(format!("https://drive.google.com/file/d/{file_id}/view")),
        attached: false,
        turned_in: false,
    };

    let spinner = Spinner::new("Attaching to the assignment");
    let result = (|| -> Result<()> {
        web.attach_drive_file(&course, &task, &file_id, &mime)?;
        record.attached = true;
        if !args.no_turn_in {
            spinner.set("Turning in");
            let after = web.turn_in(&course, &task)?;
            if after.state != State::TurnedIn {
                bail!(
                    "Classroom did not confirm the turn in (status: {})",
                    after.state.label()
                );
            }
            record.turned_in = true;
        }
        Ok(())
    })();
    drop(spinner);
    meta.last_submission = Some(record.clone());
    workspace::save(&root, &meta)?;
    result?;

    if record.turned_in {
        println!("{} Turned in.", style("✓").green().bold());
    } else {
        println!(
            "{} File attached, assignment not turned in (--no-turn-in).",
            style("✓").green().bold()
        );
    }
    Ok(())
}

pub fn unsubmit(ctx: &Ctx, path: Option<PathBuf>, yes: bool) -> Result<()> {
    let root = task_root(path)?;
    let meta = workspace::load(&root)?;
    let web = ctx.web_for(Some(&meta.account))?;
    let sub = spin("Checking assignment", || {
        web.submission(&meta.course_id, &meta.course_work_id)
    })?;
    if !sub.state.is_done() {
        println!(
            "Assignment '{}' is not turned in (status: {}).",
            meta.title,
            sub.state.label()
        );
        return Ok(());
    }
    if !yes && !confirm(&format!("Unsubmit '{}'?", meta.title), false)? {
        return Ok(());
    }
    let after = spin("Unsubmitting", || {
        web.reclaim(&meta.course_id, &meta.course_work_id)
    })?;
    println!(
        "{} Status: {}",
        style("✓").green().bold(),
        after.state.label()
    );
    Ok(())
}

pub fn status(ctx: &Ctx, path: Option<PathBuf>) -> Result<()> {
    let root = task_root(path)?;
    let meta = workspace::load(&root)?;
    let web = ctx.web_for(Some(&meta.account))?;
    let (task, sub) = spin("Fetching assignment", || -> Result<_> {
        Ok((
            web.task(&meta.course_id, &meta.course_work_id)?,
            web.submission(&meta.course_id, &meta.course_work_id).ok(),
        ))
    })?;

    println!("{}", style(&meta.title).bold());
    println!("  Course:     {}", meta.course_name);
    println!("  Due:        {}", fmt_due_long(task.due));
    println!("  Account:    {}", meta.account);
    if let Some(s) = &sub {
        let mut st = s.state.label().to_string();
        if let Some(g) = s.grade {
            st.push_str(&format!(
                ", grade: {g}{}",
                task.max_points.map(|m| format!("/{m}")).unwrap_or_default()
            ));
        }
        println!("  Status:     {st}");
        for a in &s.attachments {
            println!("  Attachment: {}", a.title);
        }
    }
    if let Some(r) = &meta.last_submission {
        println!(
            "  Last upload: {} ({})",
            r.file_name,
            &r.at[..16.min(r.at.len())]
        );
    }
    println!("\nFiles to turn in:");
    let col = workspace::collect(&root, &meta)?;
    print_files(&root, &col);
    if !col.include.is_empty() {
        println!("\nWill upload: {}", style(payload(&root, &col).name).bold());
    }
    Ok(())
}
